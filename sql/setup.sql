-- Execute in Snowflake with a role allowed to create these objects.
-- Demo warehouse is external; create/choose a warehouse in your account first.
CREATE DATABASE IF NOT EXISTS EVENT_ANALYTICS;
CREATE SCHEMA IF NOT EXISTS EVENT_ANALYTICS.RAW;
CREATE SCHEMA IF NOT EXISTS EVENT_ANALYTICS.ANALYTICS;
USE DATABASE EVENT_ANALYTICS;
USE SCHEMA RAW;

CREATE TABLE IF NOT EXISTS RAW_EVENTS (
    EVENT_ID VARCHAR(36) NOT NULL,
    EVENT_TIME TIMESTAMP_TZ NOT NULL,
    USER_ID VARCHAR(50) NOT NULL,
    MERCHANT_CATEGORY VARCHAR(40) NOT NULL,
    AMOUNT NUMBER(18,2) NOT NULL,
    COUNTRY VARCHAR(2) NOT NULL,
    CHANNEL VARCHAR(20) NOT NULL,
    DEVICE_ID VARCHAR(50),
    IS_SIMULATED_ANOMALY BOOLEAN NOT NULL,
    AI_IS_ANOMALY BOOLEAN NOT NULL,
    AI_SCORE FLOAT NOT NULL,
    AI_REASONS VARCHAR(2000),
    EVENT_PAYLOAD VARIANT,
    INGESTED_AT TIMESTAMP_TZ DEFAULT CURRENT_TIMESTAMP(),
    PRIMARY KEY (EVENT_ID) -- Informational only on standard Snowflake tables.
);

-- Snowflake standard-table primary keys are NOT enforced.
-- The application uses MERGE on EVENT_ID for replay-safe writes.
